create or replace function app.forecast_task_individual(p_run_id uuid,p_token uuid) returns jsonb
language plpgsql security definer set search_path = '' set plan_cache_mode = force_custom_plan as $$
declare r public.planning_runs; l planning.leases; result jsonb;
begin
  select * into r from public.planning_runs where id=p_run_id for update;
  if not found or r.status<>'running' or r.kind<>'forecast' then return null; end if;
  select * into l from planning.leases where run_id=r.id;
  if p_token is null or l.token is distinct from p_token or l.expires_at<=clock_timestamp() then return null; end if;
  select payload into result from planning.forecast_inputs where run_id=r.id;
  if found then return result; end if;
  with catalog as materialized (
    select id,code,name_en,status,introduced_on,discontinued_on,
      greatest(r.from_date,coalesce(introduced_on,r.from_date)) as start_day,
      least(r.to_date,coalesce(discontinued_on,r.to_date)) as end_day
    from public.items where organization_id=r.organization_id
      and code in (select jsonb_array_elements_text(r.options->'item_codes'))
  ), history as (
    select d.item_id,jsonb_agg(jsonb_build_array(d.demand_date,d.quantity::text,d.lost_sales_quantity::text) order by d.demand_date) as demand,
      count(*) rows,count(*) filter(where d.unit_of_measure is null) unknown_rows,
      array_agg(distinct d.unit_of_measure order by d.unit_of_measure) filter(where d.unit_of_measure is not null) units
    from public.demand_history d join catalog i on i.id=d.item_id
    where d.organization_id=r.organization_id and d.location_id=r.location_id
      and d.demand_date between r.from_date and r.to_date and d.demand_date between i.start_day and i.end_day
    group by d.item_id
  )
  select jsonb_build_object('kind','forecast','method',r.options->>'method','computed_at',statement_timestamp(),
    'from_date',r.from_date,'to_date',r.to_date,'options',r.options,
    'items',coalesce(jsonb_agg(jsonb_build_object('item_id',i.id,'item_code',i.code,'item_name',i.name_en,
      'status',i.status,'introduced_on',i.introduced_on,'discontinued_on',i.discontinued_on,
      'unit_provenance',app.demand_unit_evidence(h.rows,h.unknown_rows,h.units),'start_day',i.start_day,'end_day',i.end_day,'demand',coalesce(h.demand,'[]'::jsonb)) order by i.id),'[]'::jsonb))
    into result from catalog i left join history h on h.item_id=i.id;
  if jsonb_array_length(result->'items')<>jsonb_array_length(r.options->'item_codes') or octet_length(result::text)>20000000 then
    raise exception using errcode='MQ422',message='forecast input unavailable or too large';
  end if;
  if l.expires_at<=clock_timestamp() then return null; end if;
  insert into planning.forecast_inputs(run_id,payload) values(r.id,result);
  return result;
end; $$;

create or replace function app.forecast_finish_individual(p_run_id uuid,p_token uuid,p_rows jsonb) returns boolean
language plpgsql security definer set search_path = '' as $$
declare r public.planning_runs; l planning.leases; input jsonb; n integer;
begin
  select * into r from public.planning_runs where id=p_run_id for update;
  if not found or r.status<>'running' or r.kind<>'forecast' then return false; end if;
  select * into l from planning.leases where run_id=r.id;
  if p_token is null or l.token is distinct from p_token or l.expires_at<=clock_timestamp() then return false; end if;
  select payload into input from planning.forecast_inputs where run_id=r.id;
  if input is null or p_rows is null or jsonb_typeof(p_rows)<>'array' then raise exception using errcode='MQ422',message='invalid forecast output'; end if;
  n:=jsonb_array_length(input->'items');
  if jsonb_array_length(p_rows)<>n or octet_length(p_rows::text)>5000000
    or (select count(distinct x->>'item_id') from jsonb_array_elements(p_rows) x)<>n or exists(
      select 1 from jsonb_array_elements(p_rows) x where not exists(
        select 1 from jsonb_array_elements(input->'items') i where i->>'item_id'=x->>'item_id')) then
    raise exception using errcode='MQ422',message='forecast output does not match input';
  end if;
  if exists(select 1 from jsonb_array_elements(p_rows) x where
      jsonb_typeof(x->'forecast') is distinct from 'array' or jsonb_typeof(x->'scores') is distinct from 'array'
      or jsonb_typeof(x->'folds') is distinct from 'array') then
    raise exception using errcode='MQ422',message='invalid forecast evidence';
  end if;
  if exists(select 1 from jsonb_array_elements(p_rows) x where
      (x->>'status'='selected' and (jsonb_array_length(x->'forecast')<>(r.options->>'horizon')::integer
        or (r.options->>'method'='baseline-v1' and jsonb_array_length(x->'scores')<>7)
        or (r.options->>'method'='expanded-v1' and jsonb_array_length(x->'scores') not between 7 and 9)
        or jsonb_array_length(x->'folds')<>3))
      or (x->>'status'<>'selected' and (jsonb_array_length(x->'forecast')<>0 or jsonb_array_length(x->'scores')<>0))) then
    raise exception using errcode='MQ422',message='incomplete forecast evidence';
  end if;
  if r.options->>'method'='expanded-v1' and exists(select 1 from jsonb_array_elements(p_rows) x where
      jsonb_typeof(x->'uncertainty') is distinct from 'object' or jsonb_typeof(x->'evaluation') is distinct from 'object'
      or jsonb_typeof(x->'unavailable_models') is distinct from 'array'
      or jsonb_typeof(x->'uncertainty'->'bands') is distinct from 'array'
      or (x->'uncertainty'->>'status'='available' and jsonb_array_length(x->'uncertainty'->'bands')<>(r.options->>'horizon')::integer)) then
    raise exception using errcode='MQ422',message='invalid expanded forecast evidence';
  end if;
  if exists(select 1 from jsonb_array_elements(input->'items') i join jsonb_array_elements(p_rows) x on x->>'item_id'=i->>'item_id'
    where (i->'unit_provenance'->>'status'='conflicting' and x->>'status' is distinct from 'incompatible_units')
       or (x->>'status'='incompatible_units' and i->'unit_provenance'->>'status' is distinct from 'conflicting')) then
    raise exception using errcode='MQ422',message='conflicting demand units require a diagnostic result';
  end if;
  insert into public.forecast_results(organization_id,run_id,location_id,item_id,item_code,item_name,status,model,summary,evidence)
  select r.organization_id,r.id,r.location_id,(i->>'item_id')::uuid,i->>'item_code',i->>'item_name',x->>'status',x->>'model',
    jsonb_build_object('total',x->'total','scores',x->'scores'),jsonb_build_object('source',i,'output',x)
  from jsonb_array_elements(input->'items') i join jsonb_array_elements(p_rows) x on x->>'item_id'=i->>'item_id';
  if l.expires_at<=clock_timestamp() then raise exception using errcode='MQ409',message='forecast lease expired'; end if;
  update public.planning_runs set status='succeeded',finished_at=clock_timestamp(),error_code=null,
    result=jsonb_build_object('version',1,'method',r.options->>'method','computed_at',input->'computed_at','item_count',n) where id=r.id;
  perform pgmq.archive('planning',l.message_id);
  delete from planning.leases where run_id=r.id;
  return true;
end; $$;

create or replace function app.preparation_task(p_run_id uuid,p_token uuid) returns jsonb
language plpgsql security definer set search_path='' set plan_cache_mode=force_custom_plan as $$
declare r public.planning_runs; l planning.leases; result jsonb;
begin
  select * into r from public.planning_runs where id=p_run_id for update;
  if not found or r.status<>'running' or r.kind<>'preparation' then return null; end if;
  select * into l from planning.leases where run_id=r.id;
  if p_token is null or l.token is distinct from p_token or l.expires_at<=clock_timestamp() then return null; end if;
  select payload into result from planning.preparation_inputs where run_id=r.id;
  if found then return result; end if;
  -- One statement captures graph, observations and calendar under one MVCC snapshot.
  with recursive edges(a,b) as materialized (
    select predecessor_item_id,successor_item_id from public.item_supersessions where organization_id=r.organization_id and effective_on<=r.to_date
    union all select item_id,alternate_item_id from public.item_interchanges where organization_id=r.organization_id and direction='two_way'
  ), seeds as materialized (
    select id from public.items where organization_id=r.organization_id and code in (select jsonb_array_elements_text(r.options->'item_codes'))
  ), connected(id) as (
    select id from seeds union
    select case when e.a=c.id then e.b else e.a end from connected c join edges e on e.a=c.id or e.b=c.id
  ), bounded as materialized (select id from connected limit 101), catalog as materialized (
    select i.* from public.items i join bounded b on b.id=i.id where i.organization_id=r.organization_id
  ), history as (
    select d.item_id,jsonb_agg(jsonb_build_array(d.demand_date,d.quantity::text,d.lost_sales_quantity::text) order by d.demand_date) demand,
      bool_or(d.unit_of_measure<>i.unit_of_measure and d.demand_date>=coalesce(i.introduced_on,r.from_date) and d.demand_date<=coalesce(i.discontinued_on,r.to_date)) unit_conflict
    from public.demand_history d join catalog i on i.id=d.item_id
    where d.organization_id=r.organization_id and d.location_id=r.location_id and d.demand_date between r.from_date and r.to_date
    group by d.item_id
  ), context as (
    select jsonb_build_object('country',c.code,'calendar_id',w.id,'calendar_code',w.code,
      'weekend_days',coalesce(w.weekend_days,c.weekend_days),'observe_public_holidays',coalesce(w.observe_public_holidays,true),
      'active',coalesce(w.is_active,true),'coverage_from',c.holiday_coverage_from,'coverage_to',c.holiday_coverage_to,
      'holidays',coalesce((select jsonb_agg(jsonb_build_object('date',h.holiday_date,'sector',h.sector,'name',h.name_en,'source',h.source) order by h.holiday_date,h.sector)
        from public.public_holidays h where h.country_code=c.code and h.holiday_date between r.from_date and r.to_date),'[]'::jsonb),
      'windows',coalesce((select jsonb_agg(to_jsonb(v) order by v.hijri_year) from public.ramadan_windows v where v.country_code=c.code),'[]'::jsonb),
      'overrides',coalesce((select jsonb_agg(jsonb_build_object('calendar_id',o.work_calendar_id,'starts_on',o.starts_on,'ends_on',o.ends_on,'kind',o.kind,'name',o.name_en) order by o.id)
        from public.holiday_overrides o where o.organization_id=r.organization_id and (o.work_calendar_id=w.id or o.country_code=c.code)
        and o.starts_on<=r.to_date and o.ends_on>=r.from_date),'[]'::jsonb)) payload
    from public.locations loc left join public.work_calendars w on w.organization_id=loc.organization_id and w.id=loc.work_calendar_id
    join public.countries c on c.code=coalesce(w.country_code,loc.country_code)
    where loc.organization_id=r.organization_id and loc.id=r.location_id
  )
  select jsonb_build_object('kind','preparation','method','preparation-v1','computed_at',statement_timestamp(),
    'from_date',r.from_date,'to_date',r.to_date,'selected_count',(select count(*) from seeds),'calendar',(select payload from context),
    'items',(select coalesce(jsonb_agg(jsonb_build_object('item_id',i.id,'item_code',i.code,'item_name',i.name_en,'unit',i.unit_of_measure,'unit_conflict',coalesce(h.unit_conflict,false),
      'introduced_on',i.introduced_on,'discontinued_on',i.discontinued_on,'demand',coalesce(h.demand,'[]'::jsonb)) order by i.id),'[]'::jsonb)
      from catalog i left join history h on h.item_id=i.id),
    'supersessions',(select coalesce(jsonb_agg(jsonb_build_object('predecessor',s.predecessor_item_id,'successor',s.successor_item_id,'effective_on',s.effective_on,'factor',s.quantity_factor::text) order by s.id),'[]'::jsonb)
      from public.item_supersessions s where s.organization_id=r.organization_id and s.predecessor_item_id in (select id from bounded) and s.successor_item_id in (select id from bounded)),
    'interchanges',(select coalesce(jsonb_agg(jsonb_build_object('item',e.item_id,'alternate',e.alternate_item_id,'direction',e.direction) order by e.id),'[]'::jsonb)
      from public.item_interchanges e where e.organization_id=r.organization_id and e.item_id in (select id from bounded) and e.alternate_item_id in (select id from bounded))) into result;
  if (result->>'selected_count')::integer<>jsonb_array_length(r.options->'item_codes') or jsonb_array_length(result->'items') not between 1 and 100
    or result->'calendar'='null'::jsonb or octet_length(result::text)>8000000 then
    raise exception using errcode='MQ422',message='preparation input unavailable or exceeds source limits';
  end if;
  if l.expires_at<=clock_timestamp() then return null; end if;
  insert into planning.preparation_inputs(run_id,payload) values(r.id,result);
  return result;
end; $$;

create or replace function public.policy_enqueue(p_organization_id uuid,p_forecast_id uuid,p_request_id uuid,p_lead_time integer,p_review_interval integer,p_service_level numeric)
returns uuid language plpgsql security definer set search_path='' as $$
declare f public.forecast_results; source_run public.planning_runs; location_code text; run uuid; payload jsonb;
begin
  if p_organization_id is null or not(p_organization_id=any(array(select app.editable_organizations()))) then
    raise exception using errcode='MQ403',message='policy planning requires an editor';
  end if;
  if p_lead_time is null or p_lead_time not between 0 and 89 or p_review_interval is null or p_review_interval not between 1 and 90
    or p_service_level is null or p_service_level not between 0.5 and 0.999 then
    raise exception using errcode='MQ422',message='invalid policy parameters';
  end if;
  select * into f from public.forecast_results where organization_id=p_organization_id and id=p_forecast_id;
  if not found or f.status<>'selected' then raise exception using errcode='MQ422',message='choose a selected forecast'; end if;
  select * into source_run from public.planning_runs where organization_id=p_organization_id and id=f.run_id;
  if source_run.status is distinct from 'succeeded' or source_run.kind is distinct from 'forecast'
    or coalesce(source_run.options->>'method','') not in ('baseline-v1','expanded-v1','regional-v1')
    or coalesce((source_run.options->>'horizon')::integer,0)<p_lead_time+p_review_interval then
    raise exception using errcode='MQ422',message='forecast must cover the protection period';
  end if;
  select code into location_code from public.locations where organization_id=p_organization_id and id=f.location_id;
  run:=app.planning_enqueue_kind(p_organization_id,location_code,source_run.from_date,source_run.to_date,p_request_id,'policy',
    jsonb_build_object('method','policy-v1','forecast_id',p_forecast_id,'lead_time',p_lead_time,'review_interval',p_review_interval,'service_level',trim_scale(p_service_level)::text));
  -- Capture once at enqueue, including for concurrent idempotent replays. Never recreate terminal staging.
  if (select status from public.planning_runs where id=run)='queued' and not exists(select 1 from planning.policy_inputs where run_id=run) then
    payload:=jsonb_build_object('kind','policy','method','policy-v1','computed_at',statement_timestamp(),
      'options',(select options from public.planning_runs where id=run),
      'forecast',jsonb_build_object('id',f.id,'run_id',f.run_id,'item_id',f.item_id,'item_code',f.item_code,
        'unit',coalesce(f.evidence->'source'->'preparation'->>'unit',f.evidence->'source'->'unit_provenance'->>'unit'),'method',source_run.options->>'method',
        'horizon',source_run.options->'horizon','to_date',source_run.to_date,'source',f.evidence->'source','output',f.evidence->'output'));
    if octet_length(payload::text)>20000000 then raise exception using errcode='MQ422',message='policy input too large'; end if;
    insert into planning.policy_inputs(run_id,payload) values(run,payload);
  end if;
  return run;
end; $$;

create or replace view public.forecast_quality with (security_invoker=true) as
select f.id,f.organization_id,f.run_id,f.location_id,f.item_id,f.item_code,f.item_name,
  l.code as location_code,f.status,f.model,r.finished_at,r.from_date,r.to_date,
